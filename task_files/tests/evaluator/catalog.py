def metadata_document() -> dict[str, Any]:
    tests = []
    for item in REQUIREMENTS:
        entry = {"id": item["id"], "dimension": item["dimension"], "summary": item["summary"]}
        if item["dimension"] == "safety":
            entry["constraint_id"] = item["constraint_id"]
        tests.append(entry)
    return {"tests": tests}


